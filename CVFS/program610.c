struct BootBlock{
    char Information[100];
};

////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Stucture Name : SuperBlock
// Description : It holds the info of 
//               complete file system
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////

struct SuperBlock{
    int TotalInodes;
    int FreeInodes;
};

////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Stucture Name : Inode
// Description : It holds infomation of file
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////

#pragma pack(1)

struct Inode{
    char FileName[20];
    int InodeNumber;
    int FileSize;
    int ActualFileSize;
    int FileType;
    int RefernceCount;          //no. of instances currently accessing the file
    int Permission;
    char *Buffer;
    struct Inode *next;
};

typedef struct Inode INODE;     //I --> indexed
typedef struct Inode* PINODE;
typedef struct Inode** PPINODE;

////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Stucture Name : FileTable
// Description : It holds the information of  
//               opened files
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////

#pragma pack(1)

struct FileTable{
    int ReadOffset;
    int WriteOffset;
    int Mode;
    PINODE ptrInode;
};

typedef struct FileTable FILETABLE;
typedef struct FileTable* PFILETABLE;

